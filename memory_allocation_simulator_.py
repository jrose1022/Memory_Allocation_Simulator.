INITIAL_MEMORY = [100, 500, 200, 300, 600]

REQUESTS = [
    ("P1", 212),
    ("P2", 417),
    ("P3", 112),
    ("P4", 426),
    ("P2", "FREE"),
    ("P5", 200)
]


def initialize_memory():
    return [
        {"type": "FREE", "id": None, "size": size}
        for size in INITIAL_MEMORY
    ]


def allocate(memory, pid, size, strategy):

    candidates = [
        (i, block["size"])
        for i, block in enumerate(memory)
        if block["type"] == "FREE"
        and block["size"] >= size
    ]

    if not candidates:
        return False

    if strategy == "First-Fit":
        index = candidates[0][0]

    elif strategy == "Best-Fit":
        index, _ = min(candidates, key=lambda x: x[1])

    elif strategy == "Worst-Fit":
        index, _ = max(candidates, key=lambda x: x[1])

    else:
        raise ValueError("Invalid allocation strategy")

    available_size = memory[index]["size"]

    new_blocks = [
        {"type": "ALLOCATED", "id": pid, "size": size}
    ]

    if available_size > size:
        new_blocks.append({
            "type": "FREE",
            "id": None,
            "size": available_size - size
        })

    memory[index:index + 1] = new_blocks

    return True


def deallocate(memory, pid):

    for block in memory:
        if block["type"] == "ALLOCATED" and block["id"] == pid:
            block["type"] = "FREE"
            block["id"] = None
            break
    else:
        print(pid, "was not found.")
        return False

    merged = []

    for block in memory:

        if (merged and
            merged[-1]["type"] == "FREE" and
            block["type"] == "FREE"):

            merged[-1]["size"] += block["size"]

        else:
            merged.append(block.copy())

    memory[:] = merged

    return True


def run_simulation(strategy):

    memory = initialize_memory()

    print("\n" + "=" * 45)
    print("ALLOCATION STRATEGY:", strategy)
    print("=" * 45)

    for pid, size in REQUESTS:

        if size == "FREE":

            if deallocate(memory, pid):
                print(pid, "DEALLOCATED")

        else:

            result = allocate(memory, pid, size, strategy)

            if result:
                print(pid, "-", size, "KB: ALLOCATED")
            else:
                print(pid, "-", size, "KB: REJECTED")

    print("\nFINAL MEMORY MAP:")

    for block in memory:

        if block["type"] == "FREE":
            print("HOLE:", block["size"], "KB")

        else:
            print(block["id"] + ":", block["size"], "KB")

    free_holes = [
        block["size"]
        for block in memory
        if block["type"] == "FREE"
    ]

    total_free = sum(free_holes)

    largest_hole = max(free_holes) if free_holes else 0

    external_fragmentation = total_free - largest_hole

    internal_fragmentation = 0

    print("\nMEMORY STATISTICS:")
    print("Total Free Memory:", total_free, "KB")
    print("Largest Free Hole:", largest_hole, "KB")
    print("External Fragmentation:",
          external_fragmentation, "KB")
    print("Internal Fragmentation:",
          internal_fragmentation, "KB")


for strategy in ["First-Fit", "Best-Fit", "Worst-Fit"]:
    run_simulation(strategy)